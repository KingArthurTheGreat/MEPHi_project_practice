def build():
    rng = random.Random(20261105)
    rows, gold = [], []
    for label, pairs in FAMILIES.items():
        for family_index, pair in enumerate(pairs):
            split = "dev" if family_index < 6 else "test"
            family = f"{label}-{family_index}"
            for variant, text in enumerate(pair):
                rid = hashlib.sha256(f"kp2:{family}:{variant}".encode()).hexdigest()[:10]
                rows.append({"id": rid, "text": text, "label": label})
                gold.append({"id": rid, "family": family, "split": split, "acceptable_labels": [label], "is_label_error": False, "needs_review": False, "kind": "single_topic"})
    # Stratified random corruption. IDs are opaque; input CSV contains no gold fields.
    all_labels = list(FAMILIES)
    for split, count in [("dev",14),("test",10)]:
        candidates = [i for i,g in enumerate(gold) if g["split"]==split]
        for i in rng.sample(candidates,count):
            rows[i]["label"] = rng.choice([x for x in all_labels if x != rows[i]["label"]])
            gold[i].update(is_label_error=True,needs_review=True,kind="injected_error")
    for family_index,(a,b,acceptable) in enumerate(SPECIAL):
        family = f"special-{family_index}"
        split = "dev" if family_index < 6 else "test"
        for variant,text in enumerate((a,b)):
            rid = hashlib.sha256(f"kp2:{family}:{variant}".encode()).hexdigest()[:10]
            rows.append({"id":rid,"text":text,"label":acceptable[0] if acceptable else "technical"})
            gold.append({"id":rid,"family":family,"split":split,"acceptable_labels":acceptable,"is_label_error":False,"needs_review":True,"kind":"ambiguous" if acceptable else "out_of_scope"})
    rng.shuffle(rows)
    lookup = {x["id"]:x for x in gold}
    (ROOT/"data").mkdir(exist_ok=True)
    (ROOT/"evaluation").mkdir(exist_ok=True)
    for name in ["demo","dev","test"]:
        selected = rows if name=="demo" else [r for r in rows if lookup[r["id"]]["split"]==name]
        with (ROOT/f"data/{name}.csv").open("w",encoding="utf-8",newline="") as f:
            writer=csv.DictWriter(f,fieldnames=["id","text","label"])
            writer.writeheader();writer.writerows(selected)
    (ROOT/"evaluation/gold.json").write_text(json.dumps(gold,ensure_ascii=False,indent=2),encoding="utf-8")
    print(f"Built {len(rows)} synthetic rows; dev=72, test=48, injected errors=24.")

if __name__=="__main__":
    build()
