def table(rows, widths):
    cells = [[Paragraph(escape(str(value)).replace("\n", "<br/>"), styles["headcell" if i == 0 else "cell"]) for value in row] for i, row in enumerate(rows)]
    t = Table(cells, colWidths=widths, hAlign="LEFT", repeatRows=1)
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EAEDE3")),
        ("LINEBELOW", (0, 0), (-1, 0), .7, INK),
        ("LINEBELOW", (0, 1), (-1, -1), .35, LINE),
        ("LEFTPADDING", (0, 0), (-1, -1), 7), ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 9), ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
    ]))
    story.append(t)
    for i,row in enumerate(rows):
        markdown.append("| " + " | ".join(str(v).replace("\n", " ") for v in row) + " |")
        if i == 0:
            markdown.append("| " + " | ".join("---" for _ in row) + " |")
    markdown.append("")


